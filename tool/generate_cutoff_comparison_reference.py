"""Generate historical comparison envelopes, NOT estimated target scores."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]; d=root/'data/grade_cutoffs/task19'
rows=json.loads((d/'reviewed_rows.json').read_text()); exams={e['content_item_id']:e for e in json.loads((d/'registry_snapshot.json').read_text())}
def bounds(r):
 return (r['raw_score'],r['raw_score']) if r['raw_score'] is not None else (r['raw_score_min'],r['raw_score_max'])
def subject(r):
 return next(s['subject_id'] for s in exams[r['content_item_id']]['subjects'] if s['id']==r['exam_subject_id'])
out={}
for r in rows:
 if bounds(r)[0] is not None or r['standard_score'] is None:continue
 e=exams[r['content_item_id']]
 candidates=[s for s in rows if exams[s['content_item_id']]['academic_year']<e['academic_year'] and exams[s['content_item_id']]['exam_month']==e['exam_month'] and exams[s['content_item_id']]['exam_type']==e['exam_type'] and subject(s)==subject(r) and s['elective_key']==r['elective_key'] and s['grade']==r['grade'] and bounds(s)[0] is not None]
 if not candidates:continue
 sources=sorted({s['content_item_id'] for s in candidates},key=lambda k:exams[k]['academic_year'])
 out[f"{r['content_item_id']}:{r['exam_subject_id']}:{r['elective_key']}:{r['grade']}"]={'low':min(bounds(s)[0] for s in candidates),'high':max(bounds(s)[1] for s in candidates),'basis':' · '.join(f"{exams[k]['academic_year']}학년도 {str(e['exam_month'])+'월 모의평가' if e['exam_month']!=11 else '수능'}" for k in sources),'urls':[exams[k]['source_url'] for k in sources]}
assert len(out)==120

text = '// Generated by tool/generate_cutoff_comparison_reference.py. Display only.\nconst historicalCutoffReferences = <String, Map<String, dynamic>>' + json.dumps(out, ensure_ascii=False, indent=2).replace(chr(34), chr(39)) + ';\n'
(root/'lib/features/exams/cutoffs/historical_cutoff_references.dart').write_text(text)
print(f'{len(out)} historical comparison rows generated; no DB updates')
