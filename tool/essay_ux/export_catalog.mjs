// Generate APP display metadata from the existing LAB catalog. Never hand-edit IDs/order.
import fs from 'node:fs';
import path from 'node:path';
const lab=process.argv[2]; if(!lab)throw Error('Pass existing legendstudy-lab checkout');
const read=p=>JSON.parse(fs.readFileSync(path.join(lab,p),'utf8'));
const source=read('src/data/essay-public-catalog.json');
const logos=read('src/data/university-logos.json');
const policy=fs.readFileSync(path.join(lab,'src/lib/essay-runtime/catalog-policy.ts'),'utf8');
const priority=[...policy.match(/priorityUniversityIds = \[(.*?)\]/s)[1].matchAll(/'([^']+)'/g)].map(m=>m[1]);
const preparing=JSON.parse('['+policy.match(/servicePreparingUniversityIds = \[(.*?)\]/s)[1]+']');
const group=u=>preparing.includes(u.sourceUniversityId)?2:1;
const seoul=u=>u.offerings.some(o=>o.region==='서울')?0:1;
const registered=new Set(['gachon','konkuk','kyunghee','korea','dongguk','sogang','skku','sookmyung','soongsil','swu','kau']);
const rows=[...source.universities].sort((a,b)=>group(a)-group(b)||(group(a)===1?seoul(a)-seoul(b):0)||a.name.localeCompare(b.name,'ko-KR')).map(u=>({sourceUniversityId:u.sourceUniversityId,universityId:u.universityId,name:u.name,logo:logos[u.sourceUniversityId]?.src??null,officialSourceUrl:u.researchSources?.[0]?.url??(registered.has(u.sourceUniversityId)?null:u.offerings.flatMap(o=>o.sources)[0]??null)}));
const bundled=JSON.parse(fs.readFileSync('assets/university-logos/provenance.json','utf8'));
for(const row of rows){const m=bundled[row.sourceUniversityId];row.logoAsset=m?.asset??null;row.logoDark=m?.darkSurface===true;}
if(rows.length!==42||priority.length!==22)throw Error('Catalog identity count changed');
fs.writeFileSync('lib/features/essay/university_catalog.dart',`// GENERATED by tool/essay_ux/export_catalog.mjs from LAB's canonical catalog/policy.\n// 42 universities; WEB availability/Seoul/Korean alphabetical order. No exam/question IDs are duplicated.\nimport 'dart:convert';\nfinal essayUniversityCatalog = (jsonDecode(r'''${JSON.stringify(rows)}''') as List).cast<Map<String,dynamic>>();\n`);

const pdfs=read('src/data/essay-student-pdf-candidates.json').questions.filter(q=>q.verification==='VERIFIED'&&q.studentDisplay==='APPROVED'&&q.storageRead==='APPROVED');
if(new Set(pdfs.map(q=>q.questionId)).size!==pdfs.length)throw Error('Duplicate PDF question identity');
fs.writeFileSync('lib/features/essay/student_pdf_catalog.dart',`// GENERATED from deployed WEB approved question-only PDF manifest. No PDF bytes.
import 'dart:convert';
final approvedStudentPdfs = {for(final q in (jsonDecode(r'''${JSON.stringify(pdfs)}''') as List).cast<Map<String,dynamic>>()) q['questionId'] as String: q};

Map<String,dynamic>? studentPdfFor(String examId,String questionId) {
  final q=approvedStudentPdfs[questionId];
  if(q==null || q['examId']!=examId)return null;
  return {...q,'kind':'student_question','bucket':'essay-material-originals','sha256':q['assetId']};
}
`);
console.log(`Exported ${rows.length} universities and ${pdfs.length} approved question PDF mappings`);
