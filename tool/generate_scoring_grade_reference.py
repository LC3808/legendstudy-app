"""Build version-pinned practice-grade references; never alter official score data.
Owner 2026-11-11: same-exam raw => expected; comparable raw => estimated.
Only reviewed same-curriculum (2022+) subject/elective/type/month source rows.
Prefer earlier exams; if unavailable use other reviewed years for retrospective practice.
No standard-score inversion, interpolation, fabricated cutoff or DB writes.
"""
from pathlib import Path
import json, hashlib
from collections import defaultdict, Counter
R=Path(__file__).resolve().parents[1]
def read(p): return json.loads((R/p).read_text())
load=read('data/mock_expansion/task03b/load_data.json')
registry=read('data/mock_expansion/task03/registry_snapshot.json')
exams={e['content_item_id']:e for e in registry}
subjects={s['id']:s for e in registry for s in e['subjects']}
rows=read('data/grade_cutoffs/task19/reviewed_rows.json')+load['grade_cutoff_references']
electives={'언어와 매체':'언매','화법과 작문':'화작','확률과 통계':'확통','미적분':'미적','기하':'기하'}
def elective(row):
 if row.get('elective_key'): return row['elective_key']
 label=subjects[row['exam_subject_id']]['label']
 return next((k for k in electives.values() if '('+k+')' in label),'')
def bounds(row):
 v=row.get('raw_score')
 return [v,v] if v is not None else [row.get('raw_score_min'),row.get('raw_score_max')]
groups=defaultdict(lambda:defaultdict(list))
for r in rows:
 lo,hi=bounds(r)
 if lo is None or not r.get('verified_at') or not r.get('raw_source_url'): continue
 code=subjects[r['exam_subject_id']]['code']
 if not code: continue  # Unmapped subjects are not eligible for a grade.
 groups[(r['content_item_id'],code,elective(r))][r['grade']].append(r)
curves={}; keys={}; blocked=[]
for k in load['answer_key_versions']:
 assert k['verification_status']=='READY'
 cid=k['content_item_id']; e=exams[cid]; code=subjects[k['exam_subject_id']]['code']
 el=electives.get(k['paper_variant'].split(' · ')[0],'')
 curve_id=f'{cid}:{code}:{el}'
 if curve_id not in curves:
  bands=[]; sources=[]; estimated=False; missing=[]
  for g in range(1,9):
   own=groups[(cid,code,el)].get(g,[])
   candidates=own
   if not candidates:
    estimated=True
    others=[r for (other,c,el2),grades in list(groups.items())
      if other!=cid and c==code and el2==el and exams[other]['exam_type']==e['exam_type']
      and exams[other]['exam_month']==e['exam_month'] for r in grades.get(g,[])]
    prior=[r for r in others if exams[r['content_item_id']]['academic_year']<e['academic_year']]
    candidates=prior or others
   if not candidates: missing.append(g); continue
   bands.append([min(bounds(r)[0] for r in candidates),max(bounds(r)[1] for r in candidates)])
   sources.append([{'content_item_id':r['content_item_id'],'exam_subject_id':r['exam_subject_id'],
     'grade':g,'raw':bounds(r),'url':r['raw_source_url'],'digest':r['source_digest'],
     'verified_at':r['verified_at'],'revision':r['revision']} for r in candidates])
  if missing:
   blocked.append({'key':k['id'],'reason':'missing_raw_evidence','grades':missing});continue
  assert all(0<=a<=b<=k['max_score'] for a,b in bands),(curve_id,bands)
  original_bands=[list(b) for b in bands]
  # Tighten only by the required ordering of grade thresholds, never widen evidence.
  for i in range(1,8): bands[i][1]=min(bands[i][1],bands[i-1][1])
  for i in range(6,-1,-1): bands[i][0]=max(bands[i][0],bands[i+1][0])
  if any(a>b for a,b in bands):
   blocked.append({'key':k['id'],'reason':'inconsistent_raw_boundaries'});continue
  basis_ids=sorted({r['content_item_id'] for rs in sources for r in rs if r['content_item_id']!=cid},key=lambda x:exams[x]['academic_year'])
  provenance={'method':'comparable-raw-envelope-v1' if estimated else 'same-exam-raw-v1','sources':sources,'original_bands':original_bands}
  digest=hashlib.sha256(json.dumps(provenance,sort_keys=True,ensure_ascii=False).encode()).hexdigest()
  curves[curve_id]={'bands':bands,'estimated':estimated,'revision':digest,
    'basis':[f"{exams[x]['academic_year']}학년도 {str(exams[x]['exam_month'])+'월 모의평가' if exams[x]['exam_type']!='csat' else '수능'}" for x in basis_ids],
    **provenance}
 keys[k['id']]={'curve':curve_id,'exam_subject_id':k['exam_subject_id'],'variant':k['paper_variant'],
   'key_version':k['version'],'max_score':k['max_score'],'question_count':k['question_count']}
out={'method_version':'practice-grade-20261111-v1','keys':keys,'curves':curves,'blocked':blocked}
d=R/'data/mock_expansion/task03_grade_display';d.mkdir(exist_ok=True)
(d/'references.json').write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n')
# Include evidence URLs/revision in packaged reference, not user UI; no answers/PII.
compact={**out,'curves':{key:{k:v for k,v in c.items() if k!='sources'}|{'urls':sorted({r['url'] for rs in c['sources'] for r in rs})} for key,c in curves.items()}}
text='// Generated by tool/generate_scoring_grade_reference.py. Do not edit.\n'
text+="import 'dart:convert';\n\nfinal practiceGradeReferenceData = jsonDecode(r'''"+json.dumps(compact,ensure_ascii=False,separators=(',',':'))+"''') as Map<String, dynamic>;\n"
(R/'lib/features/study/scoring/practice_grade_reference_data.dart').write_text(text)
print(json.dumps({'keys':len(keys),'curves':len(curves),'by_key':dict(Counter('estimated' if curves[k['curve']]['estimated'] else 'expected' for k in keys.values())),'blocked':len(blocked)},ensure_ascii=False))
